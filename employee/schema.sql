-- Run once against the PostgreSQL database if you are managing this schema
-- outside Django migrations. admin_id is derived from the authenticated admin.
CREATE TABLE IF NOT EXISTS public.employees (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id integer NOT NULL REFERENCES public.admins(id) ON DELETE CASCADE,
    username varchar(50) NOT NULL,
    company_name varchar(100) NOT NULL,
    email varchar(100) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'EMPLOYEE',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT employee_admin_email_uniq UNIQUE (admin_id, email)
);

CREATE INDEX IF NOT EXISTS employees_admin_id_idx
    ON public.employees (admin_id);

